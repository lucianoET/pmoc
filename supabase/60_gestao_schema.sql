-- e espinha de Ishikawa (/gestao, Fase 13, Onda B)
--
-- Hoje um plano de ação da manutenção vive em planilha e um indicador
-- vive na cabeça de quem calcula. A Onda A (shared/grafico.js,
-- indicadores.js, gantt.js, abc.js, gut.js, kanban.js, calendario.js)
-- já entregou os núcleos puros que DESENHAM essas ferramentas; esta
-- migração dá a elas onde GRAVAR. Sem estas cinco tabelas o /gestao
-- seria mais um painel que lê e não registra (D-11).
--
-- PREFIXO `ges_` — a convenção de módulo já usada por `maq_`, `transp_`,
-- `elet_`, `fono_`, `pred_`, `rep_` e `cal_`. Diferente de `cmasm_`
-- (migração 49): estas cinco tabelas pertencem ao módulo /gestao, que
-- as grava; o fato de o Painel e o Calendário também LEREM outros
-- módulos (`maq_os`, `transp_*`, `logs_manutencao`, `pred_*`, `cal_*`)
-- não move o dono do dado — o mesmo raciocínio que já separa
-- `maq_areas` (D-03) de `cmasm_locais`.
--
-- ADITIVA, SEM DROP — o projeto arquiva com `ativo = false`, nunca
-- apaga uma linha. Nenhuma tabela de outro módulo é tocada: o /gestao
-- lê `maq_*`, `transp_*`, `logs_manutencao`, `pred_*` e `cal_*` pela
-- aplicação, nunca por chave estrangeira daqui para lá (D-13-03,
-- key_links) — o esquema de outro módulo não muda por causa deste.
--
-- ORDEM DE PUBLICAÇÃO (mesma regra de D-cf8-25/D-6wy/D-500): o
-- frontend do /gestao (plano 13-06) vai a produção ANTES deste SQL.
-- A sonda própria — `GES_OK`, implementada naquele plano — mantém a
-- tela publicada se comportando como se este arquivo não existisse
-- enquanto ele não rodar: sem aba de Ações, sem cartão de indicador
-- gravável, sem POP, sem espinha de Ishikawa. Na ordem inversa o
-- frontend chamaria uma tabela inexistente sem nenhum aviso.
--
-- A LIÇÃO DA MIGRAÇÃO 28, registrada aqui de novo: `create table if
-- not exists` é silêncio sobre uma tabela que já existe com outra
-- forma — aplicar sem erro não prova que a tabela ficou com a forma
-- certa. O rodapé deste arquivo traz as consultas de conferência
-- (colunas, checks, policies) para rodar DEPOIS de aplicar, não só
-- confiar no "Success" do SQL Editor.
--
-- ESCRITO E CONFERIDO, NÃO APLICADO — este plano só produz o arquivo
-- e o gate que prova a forma; a aplicação é passo humano do usuário,
-- caso a caso, depois do deploy do frontend.
