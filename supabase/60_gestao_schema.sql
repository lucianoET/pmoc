-- ── 1) ges_acoes — o 5W2H, uma linha por ação, priorizada por GUT ──
--
-- Os sete campos do 5W2H: `o_que` é o único obrigatório — uma ação sem
-- descrição não é uma ação, os outros seis podem faltar no rascunho.
--
-- `g`, `u`, `t` só aceitam a MESMA escala fechada de `shared/gut.js`
-- (`GUT_ESCALA`) ou nulo — nulo é "não avaliado", nunca zero, a mesma
-- régua de `refrig_permanente`/D-500-02: um `default` afirmaria uma
-- avaliação que não aconteceu. `gut_total` é coluna GERADA a partir do
-- produto das três — nunca um número que a tela grava por conta
-- própria, senão a prioridade mostrada e a prioridade gravada podem
-- divergir (T-13-17). A multiplicação em si já propaga o nulo: `g * u
-- * t` com qualquer uma das três nula devolve nulo, sem precisar de
-- `case` — o mesmo comportamento que `gutTotal()` implementa em
-- JavaScript para o mesmo fim.
--
-- `status` é o fluxo PDCA da ação: aberta (`planejada`), em curso
-- (`em_execucao`), sendo conferida (`verificacao`), fechada
-- (`concluida`) ou abortada (`cancelada`) — lista fechada no banco,
-- além da tela, para um estado inventado ser recusado pelo Postgres
-- (T-13-18).
--
-- `modulo` e `ativo_ref` são TEXTO LIVRE, sem chave estrangeira — o
-- /gestao lê os outros módulos, nunca amarra o esquema deles (D-13-03,
-- key_links). Uma ação pode nascer sem nenhum dos dois: nem toda ação
-- vem de um ativo (uma ação de treinamento, por exemplo).
create table if not exists ges_acoes (
  id integer generated by default as identity primary key,
  o_que text not null,
  por_que text,
  onde text,
  quando date,
  quem text,
  como text,
  quanto numeric,
  g integer check (g is null or g in (0, 1, 3, 6, 8, 10)),
  u integer check (u is null or u in (0, 1, 3, 6, 8, 10)),
  t integer check (t is null or t in (0, 1, 3, 6, 8, 10)),
  gut_total integer generated always as (g * u * t) stored,
  status text not null default 'planejada'
    check (status in ('planejada', 'em_execucao', 'verificacao', 'concluida', 'cancelada')),
  modulo text,
  ativo_ref text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  criado_por text,
  atualizado_em timestamptz not null default now()
);

-- ── 2) ges_indicadores — a definição de cada indicador ──────────────
--
-- `codigo` é único mas ANULÁVEL — mesma régua de `materiais.codigo`
-- (migração 44): um indicador pode nascer sem código curto ainda.
-- `rotulo` é obrigatório, como `materiais.nome` — um indicador sem
-- rótulo não aparece em lugar nenhum do cartão do painel.
--
-- `meta` NULA é legítima: é o indicador sem referência, que a tela
-- mostra em tom neutro em vez de fingir um alvo que ninguém definiu.
-- `sentido` diz se "maior é melhor" ou "menor é melhor" — sem ele o
-- semáforo do cartão não sabe para que lado apontar. `faixa_atencao`
-- é a fração da meta a partir da qual o estado vira atenção; nula até
-- alguém calibrar a oficina.
create table if not exists ges_indicadores (
  id integer generated by default as identity primary key,
  codigo text unique,
  rotulo text not null,
  unidade text,
  meta numeric,
  sentido text not null check (sentido in ('maior', 'menor')),
  faixa_atencao numeric,
  modulo text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

-- ── 3) ges_indicador_valores — a série histórica ────────────────────
--
-- Um valor por (indicador, período): dois valores para o mesmo mês
-- seriam duas verdades sobre o mesmo período, e é isso que a
-- unicidade abaixo impede. A unicidade em (indicador_id, periodo) já
-- serve de índice para "todos os valores deste indicador" — indicador_id
-- é a coluna líder — pelo mesmo raciocínio que a migração 44 já
-- registrou para `estoque_movimentos (os_id, tipo)`: a chave
-- estrangeira não precisa de um segundo índice só dela quando já lidera
-- um índice composto.
create table if not exists ges_indicador_valores (
  id integer generated by default as identity primary key,
  indicador_id integer not null references ges_indicadores(id) on delete cascade,
  periodo date not null,
  valor numeric not null,
  criado_em timestamptz not null default now(),
  constraint ges_indicador_valores_unico unique (indicador_id, periodo)
);

-- ── 4) ges_pop — procedimento operacional padrão ────────────────────
--
-- `titulo` é obrigatório; `texto` pode ficar vazio no rascunho. Os dois
-- vínculos (`ativo_ref`, `plano_ref`) são NULOS e INDEPENDENTES — um
-- POP sem vínculo nenhum é o caso mais comum no começo, e não é chave
-- estrangeira para tabela de outro módulo pelo mesmo motivo de
-- `ges_acoes.ativo_ref`.
create table if not exists ges_pop (
  id integer generated by default as identity primary key,
  titulo text not null,
  texto text,
  modulo text,
  ativo_ref text,
  plano_ref text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  criado_por text
);

-- ── 5) ges_causas — a espinha do Ishikawa ───────────────────────────
--
-- Pertence à ação e não sobrevive a ela: `on delete cascade` — apagar
-- (arquivar) uma ação não devia deixar causas órfãs apontando para uma
-- ação que não existe mais. `categoria` são os 6M, em caixa baixa como
-- o resto do vocabulário fechado da plataforma.
create table if not exists ges_causas (
  id integer generated by default as identity primary key,
  acao_id integer not null references ges_acoes(id) on delete cascade,
  categoria text not null
    check (categoria in ('metodo', 'maquina', 'mao_de_obra', 'material', 'medicao', 'meio_ambiente')),
  causa text not null,
  criado_em timestamptz not null default now()
);

-- ── 6) Índices ───────────────────────────────────────────────────────
--
-- Chave estrangeira sem índice é o Pitfall que a skill de boas
-- práticas mais cobra (query-missing-indexes): `ges_causas.acao_id`
-- não lidera nenhum outro índice, então ganha o seu. `indicador_id` de
-- `ges_indicador_valores` já lidera o índice da unicidade acima — ver
-- o comentário da tabela 3.
--
-- `ges_acoes` por `status` e por `modulo` são os dois recortes que a
-- tela do Painel e da aba Ações sempre pede (D-13-03/D-13-06). O mesmo
-- recorte por `modulo` se repete em `ges_pop` e `ges_indicadores`
-- porque as telas de Ferramentas/POP e do Painel filtram por módulo do
-- mesmo jeito.
create index if not exists ges_acoes_status_idx on ges_acoes (status);
create index if not exists ges_acoes_modulo_idx on ges_acoes (modulo);
create index if not exists ges_causas_acao_id_idx on ges_causas (acao_id);
create index if not exists ges_pop_modulo_idx on ges_pop (modulo);
create index if not exists ges_indicadores_modulo_idx on ges_indicadores (modulo);

-- ── 7) RLS — leitura para todo mundo, escrita para quem autenticou ──
--
-- O padrão já vigente na plataforma inteira (D-13-05): leitura aberta
-- (o cargo Livre de shared/auth.js é observador sem senha, e fechar a
-- leitura quebraria o modo observador também neste módulo) e escrita
-- para qualquer sessão que tenha feito login, SEM checar cargo dentro
-- da policy — o cargo filtra só na tela (T-13-20, aceito: mudar essa
-- régua para toda a plataforma está fora do escopo desta fase).
